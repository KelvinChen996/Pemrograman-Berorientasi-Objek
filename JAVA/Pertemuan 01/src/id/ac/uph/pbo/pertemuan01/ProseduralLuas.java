package id.ac.uph.pbo.pertemuan01;

public class ProseduralLuas {
    static double luasPersegi(double sisi)          { return sisi * sisi; }
    static double luasPersegiPanjang(double p,double l) { return p * l; }
    static double luasSegitiga(double a, double t)  { return 0.5 * a * t; }
    static double luasLingkaran(double r)           { return Math.PI * r * r; }
}
